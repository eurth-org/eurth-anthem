// The same line with a weak syllable in front turns a strong-first seven into a weak-first eight.
// Used for the lines that speak to the land: "O land of peace and land of hope".
const withO = (lines: readonly string[]): string[] =>
  lines.map((line) => {
    const [head, rest] = line.split(' | ') as [string, string];
    const lowered = /^[A-Z][a-z]/.test(rest) ? rest[0]!.toLowerCase() + rest.slice(1) : rest;
    return `${head.replace('T7', 'I8')} | O ${lowered}`;
  });

